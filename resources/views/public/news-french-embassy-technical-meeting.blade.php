    <p class="nfv-article-lead">A three-day visit beginning on 16 February 2026 brought the French Embassy in Nigeria and University of Caen Normandy experts to NfLV for the Bilingual and Competitive project.</p>
    <h2>Strengthening French education</h2>
    <p>Director and Chief Executive Officer Prof. Oladiipo Kolawole received the delegation alongside institutional leaders. Discussions considered teaching approaches, digital resources and professional opportunities connected with French studies.</p>
    <p>The visiting experts met teachers, students and ICT teams, reviewed existing teaching resources and identified training priorities. Student presentations and cultural performances formed part of the programme.</p>
    <h2>Building on the partnership</h2>
    <p>Planned follow-up included an agreement with the University of Caen Normandy, additional digital equipment and further training. The collaboration aims to improve spoken proficiency, support teachers and connect learners with employment opportunities.</p>
    <p>The visit also included an excursion around historic Badagry and a closing dinner, reinforcing the educational and cultural relationship between the institutions.</p>
